//! ASS 卡拉OK歌词生成
//!
//! 三个 Style：`orig`/`ts`/`roma`；原文行用 `{\kf<厘秒>}` 逐字，译文/罗马音为普通行。

use std::fmt::Write;

/// 逐字单元：字起始/结束毫秒 + 文本。KRC 直接给出字时长；QRC 只给起始时间，
/// 由 [`words_from_starts`] 补出 `end_ms`
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Word {
    pub start_ms: i64,
    pub end_ms: i64,
    pub text: String,
}

/// 秒 -> `00:00:03.24`（时:分:秒.厘秒）
fn format_ass_time(secs: f64) -> String {
    let total_cs = (secs * 100.0).round() as i64;
    let h = total_cs / 360_000;
    let m = (total_cs % 360_000) / 6_000;
    let s = (total_cs % 6_000) / 100;
    let cs = total_cs % 100;
    format!("{h:02}:{m:02}:{s:02}.{cs:02}")
}

fn format_ass_time_ms(ms: i64) -> String {
    format_ass_time(ms as f64 / 1000.0)
}

/// 生成 ASS 文件头 + 三个 Style（orig/ts/roma）
pub fn ass_header(title: &str) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "[Script Info]");
    let _ = writeln!(s, "; Script generated by Mercurial Player");
    let _ = writeln!(s, "Title: {title}");
    let _ = writeln!(s, "ScriptType: v4.00+");
    let _ = writeln!(s, "Timer: 100.0000");
    let _ = writeln!(s);
    let _ = writeln!(s, "[V4+ Styles]");
    let _ = writeln!(
        s,
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding"
    );
    for (name, size) in [("orig", 20u32), ("ts", 20), ("roma", 20)] {
        let _ = writeln!(
            s,
            "Style: {name},Arial,{size},&H00FFFFFF,&H000000FF,&H00000000,&H00000000,0,0,0,0,100,100,0,0,1,2,2,2,10,10,10,1"
        );
    }
    let _ = writeln!(s);
    let _ = writeln!(s, "[Events]");
    let _ = writeln!(
        s,
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text"
    );
    s
}

/// 由「字起始时间 + 文本」补出 [`Word`]：每字结束 = 下一字起始，末字结束 = `end_ms`（QQ QRC 用）
pub fn words_from_starts(segs: &[(i64, String)], end_ms: i64) -> Vec<Word> {
    segs.iter()
        .enumerate()
        .map(|(i, (start_ms, text))| Word {
            start_ms: *start_ms,
            end_ms: if i + 1 < segs.len() {
                segs[i + 1].0
            } else {
                end_ms
            },
            text: text.clone(),
        })
        .collect()
}

/// [`match_row_span`] 默认的起始时间容差：两侧时间轴同源，但各自取整可能差几毫秒
pub const MATCH_ROW_TOLERANCE_MS: i64 = 300;

/// 为译文/罗马音行挑一个原文行的起止来复用，前端按 `start-end` 合并成一行。
/// 允许 `tolerance_ms` 内最近匹配；匹配不上返回 `None`，由调用方退回自身时间轴；`spans` 须按起始时间升序。
#[must_use]
pub fn match_row_span(
    spans: &[(i64, i64)],
    start_ms: i64,
    tolerance_ms: i64,
) -> Option<(i64, i64)> {
    let at = spans.partition_point(|(s, _)| *s < start_ms);
    [at.checked_sub(1), Some(at)]
        .into_iter()
        .flatten()
        .filter_map(|i| spans.get(i))
        .min_by_key(|(s, _)| (s - start_ms).abs())
        .filter(|(s, _)| start_ms - s <= tolerance_ms && s - start_ms <= tolerance_ms)
        .copied()
}

/// 生成一条 Dialogue：`words` 多于一个单元时输出 `{\kf}` 逐字（每字时长 = 到下一字起点的
/// 区间差，末字到行尾），单单元或 `None` 时输出 `plain` 普通文本行
pub fn dialogue(
    start_ms: i64,
    end_ms: i64,
    style: &str,
    words: Option<&[Word]>,
    plain: &str,
) -> String {
    let start = format_ass_time_ms(start_ms);
    let end = format_ass_time_ms(end_ms);
    let text = match words {
        Some(words) if words.len() > 1 => {
            let mut out = String::new();
            for (i, word) in words.iter().enumerate() {
                // \kf 必须覆盖「本字起点到下一字起点」（末字到行尾），不能只写字自身时长：
                // 前端是从行首累加 \kf 反推每字起点，漏掉字间间隙会让高亮越跑越靠前，
                // 且 sum(\kf) < 行时长。KRC/yrc 给的就是字自身时长，这里换算成区间差
                let next_start = words.get(i + 1).map_or(end_ms, |w| w.start_ms);
                let kf = next_start.saturating_sub(word.start_ms).max(10) / 10; // 毫秒 -> 厘秒，至少 1
                let _ = write!(out, "{{\\kf{kf}}}{}", word.text);
            }
            out
        }
        _ => plain.to_string(),
    };
    format!("Dialogue: 0,{start},{end},{style},,0,0,0,,{text}\n")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 时间格式化为ass格式() {
        assert_eq!(format_ass_time(3.24), "00:00:03.24");
        assert_eq!(format_ass_time(61.005), "00:01:01.01");
        assert_eq!(format_ass_time(3661.0), "01:01:01.00");
    }

    #[test]
    fn 生成头与样式() {
        let header = ass_header("RISE");
        assert!(header.contains("[Script Info]"));
        assert!(header.contains("Title: RISE"));
        assert!(header.contains("Style: orig,Arial,20,"));
        assert!(header.contains("Style: ts,Arial,20,"));
        assert!(header.contains("Style: roma,Arial,20,"));
        assert!(header.contains("[Events]"));
    }

    #[test]
    fn 逐字行与普通行() {
        let words = words_from_starts(
            &[
                (3240, "徐".to_string()),
                (3380, "々".to_string()),
                (3540, "に".to_string()),
            ],
            6690,
        );
        let line = dialogue(3240, 6690, "orig", Some(&words), "");
        assert!(line.starts_with("Dialogue: 0,00:00:03.24,00:00:06.69,orig,,0,0,0,,"));
        assert!(line.contains("{\\kf14}徐"));
        assert!(line.contains("{\\kf16}々"));
        // 末字时长 = 6690-3540=3150ms -> 315 厘秒
        assert!(line.contains("{\\kf315}に"));

        let plain = dialogue(3240, 6690, "ts", None, "那缓缓变化的姿态");
        assert!(plain.starts_with("Dialogue: 0,00:00:03.24,00:00:06.69,ts,,"));
        assert!(plain.contains("那缓缓变化的姿态"));
    }

    #[test]
    fn 单字行不入逐字标记() {
        let words = vec![Word {
            start_ms: 1000,
            end_ms: 3000,
            text: "作词：李健".to_string(),
        }];
        let line = dialogue(1000, 3000, "orig", Some(&words), "作词：李健");
        assert_eq!(
            line,
            "Dialogue: 0,00:00:01.00,00:00:03.00,orig,,0,0,0,,作词：李健\n"
        );
        assert!(!line.contains("\\kf"));

        // 空单元列表同样退化为普通文本
        let empty: Vec<Word> = Vec::new();
        assert!(dialogue(0, 10, "orig", Some(&empty), "x").ends_with(",x\n"));
    }

    #[test]
    fn 逐字时长覆盖到下一字起点() {
        // KRC/yrc 给的是字自身时长，字之间有间隙；\kf 必须把间隙算进前一个字，
        // 否则前端从行首累加出来的时间点会整体靠前
        let words = vec![
            Word {
                start_ms: 0,
                end_ms: 500,
                text: "a".to_string(),
            },
            Word {
                start_ms: 1000,
                end_ms: 1400,
                text: "b".to_string(),
            },
        ];
        let line = dialogue(0, 2000, "orig", Some(&words), "");
        assert!(line.contains("{\\kf100}a"));
        assert!(line.contains("{\\kf100}b"));

        // 不变量：sum(\kf) 恰等于行时长（厘秒），字序异常也不能出现负值或 0
        let sum: u32 = kf_values(&line).iter().sum::<u32>();
        assert_eq!(sum, 200);

        let backwards = vec![
            Word {
                start_ms: 1500,
                end_ms: 1600,
                text: "a".to_string(),
            },
            Word {
                start_ms: 1000,
                end_ms: 1100,
                text: "b".to_string(),
            },
        ];
        let line = dialogue(0, 2000, "orig", Some(&backwards), "");
        // 字序倒挂时差值为负，压到下限 1 而不是产出 0 或负数
        assert_eq!(kf_values(&line), vec![1, 100]);
    }

    /// 取出一条 Dialogue 里所有 `\kf` 的厘秒值（不用正则，测试里够用）
    fn kf_values(line: &str) -> Vec<u32> {
        line.split("{\\kf")
            .skip(1)
            .map(|rest| {
                rest.chars()
                    .take_while(|c| c.is_ascii_digit())
                    .collect::<String>()
                    .parse::<u32>()
                    .unwrap()
            })
            .collect()
    }

    #[test]
    fn 译文按容差匹配原文行起止() {
        let spans = [(1000i64, 3000i64), (5000, 8000)];
        assert_eq!(match_row_span(&spans, 1000, 300), Some((1000, 3000)));
        // 取整差 200ms 仍算同一行
        assert_eq!(match_row_span(&spans, 5200, 300), Some((5000, 8000)));
        assert_eq!(match_row_span(&spans, 4900, 300), Some((5000, 8000)));
        // 超出容差与两端都要返回 None（调用方退回自身时间轴）
        assert_eq!(match_row_span(&spans, 1400, 300), None);
        assert_eq!(match_row_span(&spans, 0, 300), None);
        assert_eq!(match_row_span(&spans, 99000, 300), None);
        assert_eq!(match_row_span(&[], 1000, 300), None);
    }
}
